## 四、选机构时建议你必查的 5 条
1. **看合同+保密协议+退费条款**：正规机构都会签，且写明“未达标按约退费”。
2. **看导师同方向案例**：要求提供导师近1年发表论文 + 辅导成功案例（可脱敏）。
3. **试听/试辅导**：至少30分钟沟通，确认导师真懂你的方向。
4. **返修是否包含**：很多机构只管到“投稿”，返修要加钱；优先选套餐含返修的。
5. **拒绝“包录用/包发表/内部渠道”**：正规辅导只能提升质量，不能承诺录用。
